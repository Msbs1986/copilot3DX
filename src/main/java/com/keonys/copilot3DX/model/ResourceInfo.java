package com.keonys.copilot3DX.model;

public class ResourceInfo {

	private String name;
	private String title;
	private String description;
	private String id;
	private String type;
	private String modified;
	private String created;
	private String revision;
	private String state;
	private String owner;
	private String organization;
	private String collabspace;
	private Boolean asset;
	private String resourceType;
	private String cestamp;

	public ResourceInfo() {
	}

	public String getName() {
		return name;
	}

	public void setName(String name) {
		this.name = name;
	}

	public String getTitle() {
		return title;
	}

	public void setTitle(String title) {
		this.title = title;
	}

	public String getDescription() {
		return description;
	}

	public void setDescription(String description) {
		this.description = description;
	}

	public String getId() {
		return id;
	}

	public void setId(String id) {
		this.id = id;
	}

	public String getType() {
		return type;
	}

	public void setType(String type) {
		this.type = type;
	}

	public String getModified() {
		return modified;
	}

	public void setModified(String modified) {
		this.modified = modified;
	}

	public String getCreated() {
		return created;
	}

	public void setCreated(String created) {
		this.created = created;
	}

	public String getRevision() {
		return revision;
	}

	public void setRevision(String revision) {
		this.revision = revision;
	}

	public String getState() {
		return state;
	}

	public void setState(String state) {
		this.state = state;
	}

	public String getOwner() {
		return owner;
	}

	public void setOwner(String owner) {
		this.owner = owner;
	}

	public String getOrganization() {
		return organization;
	}

	public void setOrganization(String organization) {
		this.organization = organization;
	}

	public String getCollabspace() {
		return collabspace;
	}

	public void setCollabspace(String collabspace) {
		this.collabspace = collabspace;
	}

	public Boolean getAsset() {
		return asset;
	}

	public void setAsset(Boolean asset) {
		this.asset = asset;
	}

	public String getResourceType() {
		return resourceType;
	}

	public void setResourceType(String resourceType) {
		this.resourceType = resourceType;
	}

	public String getCestamp() {
		return cestamp;
	}

	public void setCestamp(String cestamp) {
		this.cestamp = cestamp;
	}
}